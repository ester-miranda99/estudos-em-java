// Programa para praticar a ESTRUTURA REPETITIVA FOR. 
// Contagem regressiva de um foguete fictício.

public class ContagemRegressiva {
	public static void main(String [] args) {
		System.out.println("----- PREPARAR PARA O LANÇAMENTO... ----- ");
		
		// Início      | Condição   | Passo
		for (int i = 10; i >= 0; i--) {
			System.out.println(i);
		}
		
		System.out.println("🚀 DECOLAR!");
		
	}
}